def guest_name(tech: str) -> str:
    return AROMA_MAP.get(tech, tech)


def aroma_why(tech: str) -> str:
    return AROMA_WHY.get(tech, "")


def guest_recipe(recipe):
    return [(guest_name(name), pct) for name, pct in recipe]


def guest_line(recipe):
    return " · ".join(guest_name(name) for name, _ in recipe)


def tech_line(recipe):
    return " / ".join(f"{name} {pct}" for name, pct in recipe)


